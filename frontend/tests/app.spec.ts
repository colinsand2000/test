import {test,expect} from '@playwright/test';
test('V1 tips, manual odds, isolated demo, audit log and performance',async({page})=>{
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Bättre underlag. Egna beslut.'})).toBeVisible();
 await expect(page.locator('.tip-card').first()).toBeVisible();
 await expect(page.locator('.tip-card').first()).not.toContainText('Demolag');
 await page.getByLabel('Demodata').check();
 await expect(page.locator('.tip-card')).toHaveCount(6);
 const bookmark=page.getByRole('button',{name:/^Bevaka /}).first();
 const label=await bookmark.getAttribute('aria-label');
 await bookmark.click();
 await page.getByRole('button',{name:'Min bevakning',exact:true}).click();
 await expect(page.locator('.tip-card')).toHaveCount(1);
 await page.reload();
 await page.getByLabel('Demodata').check();
 await page.getByRole('button',{name:'Min bevakning',exact:true}).click();
 await expect(page.locator('.tip-card')).toHaveCount(1);
 await page.getByRole('button',{name:'Visa analys & oddsjämförelse'}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await expect(page.getByText('Verifieringslogg',{exact:true})).toBeVisible();
 await page.getByLabel('Decimalodds HOME').fill('1,10');
 await page.getByLabel('Decimalodds DRAW').fill('10');
 await page.getByLabel('Decimalodds AWAY').fill('12');
 await page.getByRole('button',{name:'Jämför sannolikheter',exact:true}).click();
 await expect(page.getByRole('columnheader',{name:'Krävs för nollresultat'})).toBeVisible();
 await expect(page.getByText('90.9 %',{exact:true})).toBeVisible();
 await expect(page.getByText(/Oddsen är inmatade av dig och inte verifierade/)).toBeVisible();
 await page.getByRole('button',{name:'Stäng analys'}).click();
 await page.getByRole('button',{name:'Prognoslogg',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Uppföljning av förhandsprognoser'})).toBeVisible();
 await expect(page.getByRole('cell',{name:'Väntar på resultat'}).first()).toBeVisible();
 await page.getByRole('button',{name:'Modellprestanda'}).click();
 await expect(page.getByText('Reliability diagram',{exact:true})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)).toBe(false);
 await page.getByRole('button',{name:'Virtuell uppföljning'}).click();
 await expect(page.getByRole('heading',{name:'Inga virtuella observationer registrerade'})).toBeVisible();
 await page.getByRole('button',{name:'Data & metodik'}).click();
 await expect(page.getByRole('heading',{name:'Källstatus · version 1.0.0'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Synka källor nu'})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)).toBe(false);
});
